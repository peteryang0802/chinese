export function methodEvidence(id) {
  const [instruction, items, judgments] = transferChecks[id];
  const ordering = Object.keys(transferChecks).indexOf(id);
  const swap = (first, second, hint, reverse) => reverse
    ? { choices: [second, first], correct: 1, hints: [hint, ''] }
    : { choices: [first, second], correct: 0, hints: ['', hint] };
  const passages = items.map(([title, correct, distractor, hint], index) => {
    const options = swap(correct, distractor, hint, (ordering + index) % 2);
    return { ...options, title, lines: options.choices, evidence: true };
  });
  const synthesis = swap(...judgments, '把两条证据拿来检验这句话，留意它是否漏掉一个事实或说得太绝对。', ordering % 2);
  return {
    transfer: true, instruction, passages,
    synthesis: { ...synthesis, title: '哪个判断能用上这两处依据？', options: synthesis.choices },
    success: judgments[0],
  };
}
